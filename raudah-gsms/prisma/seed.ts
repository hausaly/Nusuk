/* Seed: SUPER_ADMIN + one user per role, 3 agents, 1 group with 150 pilgrims (mixed clearance), 2 hotels with rooms,
   3 arrival flights, 1 intercity trip, 4 ziyarah items. Safe to re-run (skips if the demo group exists).
   Sample ticket/visa PDFs for the extraction demo are generated by `npm run samples` into ./samples. */
import { PrismaClient, type Role } from "@prisma/client";
import bcrypt from "bcryptjs";
import { FLIGHTS, RETURNS, makePilgrims, pendingChecks } from "./seed-data";
import { airportTz, zonedToUtc } from "../src/lib/tz";
import { autoFillRooms } from "../src/services/hotels";
import { addBus, addZiyarah, autoAssignTrip, createTrip, syncAirportTrips } from "../src/services/trips";
import { ensureRules } from "../src/services/reminders";

const prisma = new PrismaClient();
const password = process.env.SEED_DEFAULT_PASSWORD ?? "Raudah#2026";
const adminEmail = process.env.SEED_SUPERADMIN_EMAIL ?? "admin@raudah.test";
const KSA = "Asia/Riyadh";

async function main() {
  if (process.env.NODE_ENV === "production" && !process.env.SEED_DEFAULT_PASSWORD)
    throw new Error("Refusing to seed production with the default password. Set SEED_DEFAULT_PASSWORD.");
  const passwordHash = await bcrypt.hash(password, 12);

  const agents = await Promise.all(
    [
      { groupName: "Al-Huda Travels", contactName: "Musa Abdullahi", phone: "+2348030000001", email: "alhuda@agents.raudah.test" },
      { groupName: "Zamzam Hajj & Umrah Services", contactName: "Fatima Bello", phone: "+2348030000002", email: "zamzam@agents.raudah.test" },
      { groupName: "Safa Marwa Tours", contactName: "Ibrahim Yusuf", phone: "+2348030000003", email: "safamarwa@agents.raudah.test" },
    ].map((a) => prisma.agent.upsert({ where: { groupName: a.groupName }, update: {}, create: a })),
  );

  const staff: { name: string; email: string; role: Role; agentId?: string; phone?: string }[] = [
    { name: "Super Admin", email: adminEmail, role: "SUPER_ADMIN" },
    { name: "Visa Officer", email: "visa@raudah.test", role: "VISA_OFFICER", phone: "+2348030000011" },
    { name: "Ticket Officer", email: "ticket@raudah.test", role: "TICKET_OFFICER", phone: "+2348030000012" },
    { name: "Finance Staff", email: "finance@raudah.test", role: "FINANCE_STAFF", phone: "+2348030000013" },
    { name: "Operations Staff", email: "ops@raudah.test", role: "OPERATIONS_STAFF", phone: "+2348030000014" },
    { name: "Al-Huda Agent", email: "agent@raudah.test", role: "AGENT", agentId: agents[0].id },
  ];
  for (const u of staff) await prisma.user.upsert({ where: { email: u.email }, update: {}, create: { ...u, passwordHash } });
  await ensureRules();

  if (await prisma.group.findUnique({ where: { code: "UMR-2026-001" } })) { console.log("Demo group already seeded."); return; }
  const admin = await prisma.user.findUniqueOrThrow({ where: { email: adminEmail } });
  const ops = await prisma.user.findUniqueOrThrow({ where: { email: "ops@raudah.test" } });
  const actor = { id: admin.id, role: admin.role as Role };

  const group = await prisma.group.create({
    data: { code: "UMR-2026-001", name: "Umrah December 2026", startDate: new Date("2026-12-01T00:00:00Z"), endDate: new Date("2026-12-12T00:00:00Z"), arrivalAirport: "JED", departureAirport: "MED", status: "ACTIVE", supervisorId: ops.id, agents: { create: agents.map((a) => ({ agentId: a.id })) } },
  });

  // ---- pilgrims (+ checks, tickets, visas for cleared checks)
  const demo = makePilgrims(150);
  for (const p of demo) {
    const pending = pendingChecks(p);
    const created = await prisma.pilgrim.create({
      data: {
        groupId: group.id, agentId: agents[p.agentIdx].id, fullName: p.fullName, passportNo: p.passportNo, passportExpiry: new Date(p.passportExpiry + "T00:00:00Z"), dateOfBirth: new Date(p.dob + "T00:00:00Z"),
        gender: p.gender, phoneNigeria: "+234" + p.phone.slice(1), emergencyContactName: "Next of kin", emergencyContactPhone: "+2348099990000", familyLinkId: p.familyLinkId, specialNeeds: p.specialNeeds,
        checks: { create: (["PAYMENT", "DOCUMENTS", "VISA", "TICKET"] as const).map((type) => ({ type, status: pending.includes(type) ? "PENDING" : "CLEARED", updatedById: pending.includes(type) ? null : admin.id })) },
      },
    });
    const f = FLIGHTS[p.flight], rt = RETURNS[p.ret];
    if (!pending.includes("TICKET"))
      await prisma.ticket.create({ data: { pilgrimId: created.id, pnr: p.pnr, ticketNo: p.ticketNo, airline: f.airline,
        outFlightNo: f.no.replace(" ", ""), outDepartureAirport: f.dep, outDepartureAt: zonedToUtc(f.depAt, airportTz(f.dep)), outArrivalAirport: f.arr, outArrivalAt: zonedToUtc(f.arrAt, KSA),
        retFlightNo: rt.no.replace(" ", ""), retDepartureAirport: rt.dep, retDepartureAt: zonedToUtc(rt.depAt, KSA), retArrivalAirport: rt.arr, retArrivalAt: zonedToUtc(rt.arrAt, airportTz(rt.arr)) } });
    if (!pending.includes("VISA"))
      await prisma.visa.create({ data: { pilgrimId: created.id, visaNo: p.visaNo, issueDate: new Date("2026-10-15T00:00:00Z"), expiryDate: new Date("2027-02-15T00:00:00Z"), permittedStayDays: 30, entryType: "Umrah – Single entry" } });
  }

  // ---- hotels + rooms
  const makkah = await prisma.hotel.create({ data: { groupId: group.id, name: "Raudah Al-Safa Hotel", city: "MAKKAH", address: "Ajyad Street, Makkah", contactPhone: "+966125550101" } });
  const madinah = await prisma.hotel.create({ data: { groupId: group.id, name: "Dar Al-Taqwa Madinah", city: "MADINAH", address: "Central Area, Madinah", contactPhone: "+966145550202" } });
  for (const [h, base] of [[makkah, 100], [madinah, 200]] as const)
    await prisma.room.createMany({ data: Array.from({ length: 40 }, (_, i) => ({ hotelId: h.id, roomNo: String(base + i + 1), type: "QUAD" as const, capacity: 4, gender: i < 14 ? ("M" as const) : i < 28 ? ("F" as const) : null })) });

  // ---- trips: 3 arrival flights + 2 return flights (from tickets), intercity, ziyarah
  await syncAirportTrips(prisma, group.id);
  await createTrip(actor, group.id, { type: "INTERCITY", title: "Makkah → Madinah", fromCity: "MAKKAH", toCity: "MADINAH", scheduledAt: zonedToUtc("2026-12-07T08:00", KSA).toISOString() });
  for (const [site, city, at] of [["Jabal Al-Noor & Cave of Hira", "MAKKAH", "2026-12-04T09:00"], ["Mina, Muzdalifah & Arafat", "MAKKAH", "2026-12-05T09:00"], ["Masjid Quba", "MADINAH", "2026-12-09T09:00"], ["Mount Uhud & Martyrs' cemetery", "MADINAH", "2026-12-09T15:00"]] as const)
    await addZiyarah(actor, group.id, { site, city, scheduledAt: zonedToUtc(at, KSA).toISOString() });

  // ---- some planning already done so the demo has data: rooming in Makkah, bus on the first arrival flight
  await autoFillRooms(actor, makkah.id);
  const first = await prisma.trip.findFirstOrThrow({ where: { groupId: group.id, type: "ARRIVAL_PICKUP" }, orderBy: { scheduledAt: "asc" } });
  await addBus(actor, first.id, { company: "Al-Haramain Transport", companyPhone: "+966500000001", vehiclePlate: "KSA 4521", busNo: "B1", driverName: "Khalid Al-Otaibi", driverPhone: "+966500000002", staffInChargeId: ops.id });
  await addBus(actor, first.id, { company: "Al-Haramain Transport", vehiclePlate: "KSA 4522", busNo: "B2", driverName: "Faisal Al-Harbi", driverPhone: "+966500000003", staffInChargeId: ops.id });
  await autoAssignTrip(actor, first.id);

  console.log(`Seeded group UMR-2026-001 with ${demo.length} pilgrims; ${staff.length} users, ${agents.length} agents. Password for all users: ${password}`);
}

main().finally(() => prisma.$disconnect());
